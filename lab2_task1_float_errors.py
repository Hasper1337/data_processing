"""ЛР №2, задание 1: ошибки представления чисел (IEEE 754) в Python.

В Python обычное число float - это double (64 бита), а в примерах на C
использовался float (32 бита). Поэтому для повторения ошибок берём
numpy.float32 (одинарная точность).
"""
import numpy as np

f32 = np.float32

print("1. Точность IEEE754")
a = f32(123456789)
b = f32(123456788)
print("   float32:", a - b, "(должно быть 1.0)")
print("   float64:", 123456789.0 - 123456788.0)

print("2. Приведение типов (single и double)")
a = f32(123456789.123457)      # хранится как single
b = 123456789.123457           # хранится как double
print("   разность:", float(a) - b, "(должно быть 0)")

print("3. Промежуточные данные")
a, b = f32(1), f32(3)
c = a / b
c = c - f32(1) / f32(3)
print("   1/3 - 1/3 (float32):", c)
c = f32(1) / f32(3)
c = float(c) - 1 / 3           # float32 минус double
print("   float32 - double   :", c, "(должно быть 0)")
print("   0.6000006 + 0.09999994 =", f32(0.6000006) + f32(0.09999994))

print("4. Сдвиг мантисс (бункер с таблетками)")
c = f32(300)                   # вес бункера, кг
a = f32(0.00001)               # вес таблетки, кг
for n in range(1, 10000000):
    c = c - a
print("   вес бункера:", c, "(должно быть около 200)")

print("5. Коммутативность (сложение в разном порядке)")
# В примере 1e9 шагов - это очень долго, берём 1e6
N = 1000000
step = 1 / N
down = 100.0
up = 0.0
for i in range(N):
    down -= step
    up += step
print("   вниз от 100:", down, "(должно быть 99.0)")
print("   вверх от 0 :", up, "(должно быть 1.0)")
print("   сумма в одну сторону и в другую даёт разные ошибки")

print("6. Ошибки в циклах")
x = 0.2
found = False
for i in range(40):
    x -= 0.1
    if x == 0:
        print("   ok на шаге", i + 1)
        found = True
if not found:
    print("   x == 0 ни разу не выполнилось, x =", x)
x = 0.2
found = False
for i in range(40):
    x -= 0.01
    if x == 0:
        print("   (0.01) ok на шаге", i + 1)
        found = True
if not found:
    print("   (0.01) x == 0 ни разу не выполнилось, x =", x)

print()
print("Вывод: вещественные числа хранятся приближённо, поэтому их нельзя")
print("сравнивать через ==, лучше использовать abs(a - b) < eps.")
